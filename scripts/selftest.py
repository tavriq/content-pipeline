def run_lint(text: str) -> tuple[int, str]:
    with tempfile.NamedTemporaryFile("w", suffix=".md", encoding="utf-8", delete=False) as handle:
        handle.write(text)
        path = Path(handle.name)
    try:
        result = subprocess.run(
            [sys.executable, str(LINT), str(path)],
            capture_output=True,
            text=True,
        )
        return result.returncode, result.stdout + result.stderr
    finally:
        path.unlink(missing_ok=True)


def main() -> int:
    failures: list[str] = []

    for name, text, should_hit in CASES:
        code, output = run_lint(text)
        if code == 2:
            failures.append(f"{name}: линтер не запустился\n{output.strip()}")
            continue
        hit = code == 1
        if hit is not should_hit:
            expected = "срабатывание" if should_hit else "чисто"
            got = "сработал" if hit else "пропустил"
            detail = "\n".join(f"    {line}" for line in output.strip().splitlines()[:6])
            failures.append(f"{name}: ожидалось {expected}, линтер {got}\n{detail}")
        print(f"[{'ok' if hit is should_hit else '!!'}] {name}")

    print()
    if failures:
        print(f"Провалено {len(failures)} из {len(CASES)}:\n")
        for item in failures:
            print(item, "\n")
        return 1

    print(f"Все {len(CASES)} кейсов прошли.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
